const ESTIMATED_IMAGE_CHARS = 4800;

function estimateTextAndImageContentChars(content: string | Array<{ type: string; text?: string }>): number {
	if (typeof content === "string") {
		return content.length;
	}

	let chars = 0;
	for (const block of content) {
		if (block.type === "text" && block.text) {
			chars += block.text.length;
		} else if (block.type === "image") {
			chars += ESTIMATED_IMAGE_CHARS;
		}
	}
	return chars;
}

/**
 * 用 chars/4 启发式估算一条消息的 token 数。
 * 这是保守做法（会高估 tokens）。
 */
export function estimateTokens(message: AgentMessage): number {
	let chars = 0;

	switch (message.role) {
		case "system": {
			const system = message as SystemMessage;
			chars = estimateTextAndImageContentChars(system.content);
			if (system.sections) {
				for (const section of Object.values(system.sections)) {
					if (section) chars += section.length;
				}
			}
			if (system.toolsAdded) chars += JSON.stringify(system.toolsAdded).length;
			return Math.ceil(chars / 4);
		}
		case "user": {
			chars = estimateTextAndImageContentChars(
				(message as { content: string | Array<{ type: string; text?: string }> }).content,
			);
			return Math.ceil(chars / 4);
		}
		case "assistant": {
			const assistant = message as AssistantMessage;
			for (const block of assistant.content) {
				if (block.type === "text") {
					chars += block.text.length;
				} else if (block.type === "thinking") {
					chars += block.thinking.length;
				} else if (block.type === "toolCall") {
					chars += block.name.length + JSON.stringify(block.arguments).length;
				}
			}
			return Math.ceil(chars / 4);
		}
		case "custom":
		case "toolResult": {
			chars = estimateTextAndImageContentChars(message.content);
			return Math.ceil(chars / 4);
		}
		case "bashExecution": {
			chars = message.command.length + message.output.length;
			return Math.ceil(chars / 4);
		}
		case "branchSummary":
		case "compactionSummary": {
			chars = message.summary.length;
			return Math.ceil(chars / 4);
		}
	}

	return 0;
}

function isCutPointMessage(message: AgentMessage): boolean {
	switch (message.role) {
		case "user":
		case "assistant":
		case "bashExecution":
		case "custom":
		case "branchSummary":
		case "compactionSummary":
			return true;
		case "toolResult":
			return false;
	}
	return false;
}

function isTurnStartMessage(message: AgentMessage): boolean {
	switch (message.role) {
		case "user":
		case "bashExecution":
		case "custom":
		case "branchSummary":
		case "compactionSummary":
			return true;
		case "assistant":
		case "toolResult":
			return false;
	}
	return false;
}

function isTurnStartEntry(entry: SessionEntry): boolean {
	if (entry.type === "compaction") {
		return false;
	}
	return sessionEntryToContextMessages(entry).some(isTurnStartMessage);
}

/**
 * 找出有效的切分点：context 可见的类用户或 assistant 消息的索引。
 * 绝不在 tool 结果处切分（它们必须跟在自己的 tool call 之后）。
 * 在带 tool call 的 assistant 消息处切分时，其后的 tool 结果会保留。
 */
function findValidCutPoints(entries: SessionEntry[], startIndex: number, endIndex: number): number[] {
	const cutPoints: number[] = [];
	for (let i = startIndex; i < endIndex; i++) {
		const entry = entries[i];
		if (entry.type === "compaction") {
			continue;
		}
		if (sessionEntryToContextMessages(entry).some(isCutPointMessage)) {
			cutPoints.push(i);
		}
	}
	return cutPoints;
}

/**
 * 找到开启包含给定 entry index 的 turn 的 context 可见 user 消息。
 * 若在索引之前找不到 turn 起点，返回 -1。
 */
export function findTurnStartIndex(entries: SessionEntry[], entryIndex: number, startIndex: number): number {
	for (let i = entryIndex; i >= startIndex; i--) {
		if (isTurnStartEntry(entries[i])) {
			return i;
		}
	}
	return -1;
}

export interface CutPointResult {
	/** 要保留的第一个 entry 的索引 */
	firstKeptEntryIndex: number;
	/** 被切分 turn 的起始 user 消息索引，未切分则为 -1 */
	turnStartIndex: number;
	/** 本次切分是否将一个 turn 拦腰截断（切分点不是 user 消息） */
	isSplitTurn: boolean;
}

/**
 * 在 session entries 中找切分点，使保留部分约等于 `keepRecentTokens`。
 *
 * 算法：从最新的条目向前走，累加估算的消息大小。
 * 当累计 >= keepRecentTokens 时停下来，在该点切分。
 *
 * 可以在 user 或 assistant 消息处切分（绝不在 tool 结果处）。
 * 在带 tool call 的 assistant 消息处切分时，其后的 tool 结果会保留。
 *
 * 返回的 CutPointResult 包含：
 * - firstKeptEntryIndex：开始保留的 entry 索引
 * - turnStartIndex：若在 turn 中途切分，即开启该 turn 的 user 消息
 * - isSplitTurn：是否在 turn 中途切分
 *
 * 只考虑 `startIndex` 到 `endIndex` 之间（不含）的 entries。
 */
export function findCutPoint(
	entries: SessionEntry[],
	startIndex: number,
	endIndex: number,
	keepRecentTokens: number,
): CutPointResult {
	const cutPoints = findValidCutPoints(entries, startIndex, endIndex);

	if (cutPoints.length === 0) {
		return { firstKeptEntryIndex: startIndex, turnStartIndex: -1, isSplitTurn: false };
	}

	// 从最新的条目向前走，累加估算的消息大小
	let accumulatedTokens = 0;
	let cutIndex = cutPoints[0]; // 默认：从第一条消息开始保留（不含 header）

	for (let i = endIndex - 1; i >= startIndex; i--) {
		const entry = entries[i];
		const messageTokens = sessionEntryToContextMessages(entry).reduce(
			(sum, message) => sum + estimateTokens(message),
			0,
		);
		if (messageTokens === 0) continue;
		accumulatedTokens += messageTokens;

		// 检查是否超出预算
		if (accumulatedTokens >= keepRecentTokens) {
			// 优先选择本 entry 处或之后最近的合法切分点。若尾部 tool 结果
			// 自身就超预算，则保留其前面的 assistant tool call，
			// 而不是退回到第一条消息。
			cutIndex = cutPoints.find((candidate) => candidate >= i) ?? cutPoints[cutPoints.length - 1];
			break;
		}
	}

	// 从 cutIndex 向前扫描，把不影响 context 的相邻 metadata entries 一并纳入。
	while (cutIndex > startIndex) {
		const prevEntry = entries[cutIndex - 1];
		// 遇到 compaction 边界或 context 可见的 entry 时停止。
		if (prevEntry.type === "compaction" || sessionEntryToContextMessages(prevEntry).length > 0) {
			break;
		}
		cutIndex--;
	}

	// 判断这是否为 split turn
	const cutEntry = entries[cutIndex];
	const startsTurn = isTurnStartEntry(cutEntry);
	const turnStartIndex = startsTurn ? -1 : findTurnStartIndex(entries, cutIndex, startIndex);

	return {
		firstKeptEntryIndex: cutIndex,
		turnStartIndex,
		isSplitTurn: !startsTurn && turnStartIndex !== -1,
	};
}

